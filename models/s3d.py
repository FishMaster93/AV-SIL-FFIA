class S3D(nn.Module):
    def __init__(self, num_classes=400):
        super().__init__()
        self.base = nn.Sequential(
            SepConv3d(3, 64, kernel_size=7, stride=2, padding=3),
            nn.MaxPool3d(kernel_size=(1, 3, 3), stride=(1, 2, 2), padding=(0, 1, 1)),
            BasicConv3d(64, 64, kernel_size=1, stride=1),
            SepConv3d(64, 192, kernel_size=3, stride=1, padding=1),
            nn.MaxPool3d(kernel_size=(1, 3, 3), stride=(1, 2, 2), padding=(0, 1, 1)),
            Mixed_3b(),
            Mixed_3c(),
            nn.MaxPool3d(kernel_size=(3, 3, 3), stride=(2, 2, 2), padding=(1, 1, 1)),
            Mixed_4b(),
            Mixed_4c(),
            Mixed_4d(),
            Mixed_4e(),
            Mixed_4f(),
            nn.MaxPool3d(kernel_size=(2, 2, 2), stride=(2, 2, 2), padding=(0, 0, 0)),
            Mixed_5b(),
            Mixed_5c(),
        )
        self.fc = nn.Sequential(nn.Conv3d(1024, num_classes, kernel_size=1, stride=1, bias=True))

    @staticmethod
    def normalize(x):
        """uint8 (B,T,H,W,3) -> float (B,3,T,H,W)，范围 [-1,1]（kylemin/S3D 的预处理）。"""
        if x.dtype == torch.uint8:
            x = x.permute(0, 4, 1, 2, 3).float().div_(255.0)
        else:
            x = x.transpose(1, 2)
        return x.mul(2.0).sub_(1.0)

    def forward_features(self, x):
        """返回最后一层特征图 (B, 1024, T', H', W')。"""
        return self.base(self.normalize(x))

    def forward(self, x):
        fmap = self.forward_features(x)
        embedding = fmap.mean(dim=(2, 3, 4))                       # (B, 1024)
        logits = self.fc(fmap.mean(dim=(3, 4), keepdim=True)).mean(dim=(2, 3, 4))
        return {'logits': logits, 'embedding': embedding, 'fmap': fmap}


def load_s3d_kinetics(model, path='Pre_trained_model/S3D400.pt', load_fc=False):
    """加载 Kinetics-400 权重。默认不加载 400 类分类头；所有骨干参数必须全部对上，否则报错。"""
    sd = torch.load(path, map_location='cpu')
    sd = {k[len('module.'):] if k.startswith('module.') else k: v for k, v in sd.items()}
    if not load_fc:
        sd = {k: v for k, v in sd.items() if not k.startswith('fc.')}
    missing, unexpected = model.load_state_dict(sd, strict=False)
    missing = [k for k in missing if not k.startswith('fc.')]
    if missing or unexpected:
        raise RuntimeError(f'S3D 权重不匹配: missing={missing[:5]} unexpected={unexpected[:5]}')
    return model
